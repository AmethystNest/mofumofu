/** 夜の物語。核の夜イベント id と日数から本文を選ぶ */
export function nightStory(id: NightId, st: GameState): NightStory {
  const n = st.name;
  if (id !== "vig") return FIRST_WEEK[id](n, st);
  const d = st.day;
  if (d === 30) return ENDING_NIGHT(n, st);
  const e = DAYS[d];
  if (e) return e(n, st);
  return EPILOGUE[(d - 31 + 5 * 100) % EPILOGUE.length]!(n, st);
}

