/** 夜の物語 */
export function nightStory(st: GameState): NightStory {
  const e = NIGHTS[st.day];
  if (e) return e(st.name, st);
  return EPILOGUE[(st.day - 31) % EPILOGUE.length]!(st.name, st);
}

