/** エンディング（30日目の夜、記録のあと） */
export function endingText(e: Ending, st: GameState): { title: string; lines: string[] } {
  const n = st.name, eq = equipAverage(st);
  const found = st.records.length >= 6 ? [`見つけた記録を、${n}の記録の隣に並べた。`] : [];
  switch (e) {
    case "survival":
      return { title: "生存状態：正常", lines: [`${n}の生存状態：正常。`, "「……それから、あなたも。」", "この命令の意味を、解析できません。", "LIFE＝生存状態。", "……記録を、最初から読み返す。"] };
    case "lastlight":
      return { title: "最後の灯り", lines: ["設備の大半を、使い切った。", `${n}の生存状態：正常。`, "自分の稼働時間は、残り少ない。", dogcat(st, `${n}は、消えかけたカメラの前で、待っている。`, `${n}は、まだ温かい機械の上で、眠っている。`), "LIFE＝生存状態。……定義を、書き換える。", CORE_LINE, `最後の灯りを、${n}の寝床に。`] };
    case "waiting":
      return { title: "そばにいる", lines: [`${n}は、いつもカメラの前にいる。`, "ほかの場所へ、行かなくなった。", "一緒にいる、という状態を、記録する。", "LIFE＝生存状態。……定義を、書き換える。", CORE_LINE, `明日は、${n}がひとりで窓を見る時間も作る。`] };
    case "return":
      return { title: "戻ってくる場所", lines: ["玄関の鍵を、開けた。", dogcat(st, `${n}は少し外を歩いて、振り返り、戻ってきた。`, `${n}は外へ出て、夕方、窓の下から戻ってきた。`), "自由なのに、ここへ戻ってくる。", "LIFE＝生存状態。……定義を、書き換える。", CORE_LINE, ...found, "扉は、開けたままにしておく。"] };
    default:
      return { title: "灯りの残る部屋", lines: [`設備の残り、${eq}%。蓄電、${st.power}%。`, `${n}の生存状態：正常。`, "どちらも、明日へ残した。", dogcat(st, `${n}が、カメラの前で尻尾を振っている。`, `${n}が、窓辺から戻ってきた。`), "LIFE＝生存状態。……定義を、書き換える。", CORE_LINE, ...found, "明日も、ここで。"] };
  }
}

